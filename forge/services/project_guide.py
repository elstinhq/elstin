"""The project guide the planner and dev agents read before they work.

A repo that ships an AGENTS.md (or CLAUDE.md) tells the agents its layout,
its commands and what already exists, so they do not rediscover it every run
— or get it wrong. One run planned a brand-new codegen script for a repo whose
`package.json` already had one, because nothing had told it to look. This
module finds that guide and, for a repo that has none, can write one.

Precedence, per repo: the repo's own AGENTS.md, then CLAUDE.md, then the
guide forge generated and stored for it, then nothing. A guide the repo
ships always wins — a human wrote it — and forge never writes into a
checkout: the generated guide lives on `ProjectRepo.generated_guide`.

Generation is one single-shot model call over facts gathered by walking the
repo (`gather_repo_facts`): a shallow listing, manifests, READMEs, CI
workflows and a code skeleton. The prompt is built around the failure that
made this worth having — a guide that says something is *missing* when the
listing merely did not show it — so the model is told to state only what the
material shows, to copy commands verbatim, and never to claim an absence.
It is off by default (`generate_project_guide`), because it spends tokens on
a repo nobody asked it to describe.
"""
from __future__ import annotations

import asyncio
import logging
import os
from typing import Any

from forge.config.store import resolve_bool_config
from forge.llm.registry import LlmNotConfiguredError
from forge.services.generation import GenerationError, chat_completion_json
from forge.tools.codebase_skeleton import build_codebase_skeleton
from forge.tools.grep import DEFAULT_EXCLUDES

logger = logging.getLogger("forge.project_guide")

# Looked for at a repo's root, in this order.
GUIDE_FILENAMES = ("AGENTS.md", "CLAUDE.md")
# Per guide. The prompt carries it on every planner turn, so a long one is a
# standing tax; this is roughly 2k tokens.
MAX_GUIDE_CHARS = 8_000

GENERATED_HEADER = (
    "<!-- Generated by code_forge from this repo's manifests, README and CI files. "
    "Where it disagrees with the repo, the repo wins. -->"
)

# What `gather_repo_facts` looks for at the root and one level down (a
# monorepo keeps its manifests a folder in). Filenames only — nothing here
# interprets them; the model reads what they say.
_MANIFESTS = (
    "package.json", "pom.xml", "build.gradle", "build.gradle.kts", "settings.gradle", "pyproject.toml",
    "setup.cfg", "requirements.txt", "go.mod", "Cargo.toml", "Gemfile", "pubspec.yaml", "composer.json",
    "Makefile", "Dockerfile", "docker-compose.yml", "docker-compose.yaml",
)
_READMES = ("README.md", "README.rst", "README.txt", "README")
_MANIFEST_CHARS = 2_500
_README_CHARS = 2_500
_WORKFLOW_CHARS = 2_000
_MAX_WORKFLOWS = 4
_TREE_CHARS = 3_500
_SKELETON_CHARS = 4_000
_FACTS_CHARS = 26_000
# Directory names to skip when walking. DEFAULT_EXCLUDES also holds nested
# paths ("ios/build"), which a per-name check can't use.
_SKIP_DIRS = frozenset(name for name in DEFAULT_EXCLUDES if "/" not in name) | {"target", "dist", ".idea", ".gradle"}

_GUIDE_SCHEMA = {
    "type": "object",
    "properties": {"guide": {"type": "string"}},
    "required": ["guide"],
    "additionalProperties": False,
}

_SYSTEM_PROMPT = """You write AGENTS.md: a short guide that coding agents read before planning or changing a repository. You are given raw material gathered from the repo — a directory listing, manifests, READMEs, CI workflows and a code skeleton.

Rules:
- State only what the material shows. Never guess.
- Copy commands verbatim from manifests, READMEs or CI files. Never invent a command, script, file or dependency.
- The listing and the skeleton are partial views of the repo. Never say something is missing, absent or "not yet present" — say nothing about what you cannot see.
- Include an "Already exists — do not recreate" section naming the scripts, config files, generated files and test setups the material shows, so an agent does not add a second copy.
- If a file is generated (a header says so, or a README or script names its source), say how to regenerate it and that it must not be edited by hand.
- Omit any section you have no evidence for. Short and correct beats long and complete.
- Markdown, about 60 lines at most, no preamble. Suggested sections: Overview, Layout, Commands, Tests, Generated files, Already exists — do not recreate."""


class GuideError(RuntimeError):
    """A guide that could not be generated: nothing to describe, no model
    configured, or the model's reply was unusable."""


def read_repo_guide(repo_path: str) -> tuple[str, str] | None:
    """(filename, text) of the repo's own guide, or None. A file that is
    empty or unreadable counts as absent."""
    for name in GUIDE_FILENAMES:
        try:
            with open(os.path.join(repo_path, name), encoding="utf-8") as fh:
                text = fh.read().strip()
        except (OSError, UnicodeDecodeError):
            continue
        if text:
            return name, text
    return None


def _cap(text: str, limit: int = MAX_GUIDE_CHARS) -> str:
    return text if len(text) <= limit else text[:limit].rstrip() + "\n\n[guide truncated]"


def resolve_project_guide(roots: dict[str, str], generated_by_path: dict[str, str]) -> dict[str, Any]:
    """The guide for a run, in the shape the planner and dev prompts read
    (`found`, `path`, `content`). One repo's guide is passed through as is;
    several are joined under a heading each, since the reader has to know
    which repo a rule belongs to.

    `generated_by_path` is {repo path: generated guide}; a repo's own file
    takes precedence over an entry there."""
    entries: list[tuple[str, str, str]] = []  # (label, source, text)
    for label, path in roots.items():
        own = read_repo_guide(path)
        if own:
            entries.append((label, own[0], own[1]))
        elif generated_by_path.get(path):
            entries.append((label, "generated by forge", generated_by_path[path]))
    if not entries:
        return {"found": False}

    if len(entries) == 1:
        text = _cap(entries[0][2])
    else:
        text = "\n\n".join(f"### {label} ({source})\n\n{_cap(body)}" for label, source, body in entries)
    return {
        "found": True,
        "path": ", ".join(sorted({source for _, source, _ in entries})),
        "content": text,
        "generated": any(source == "generated by forge" for _, source, _ in entries),
    }


def _read_head(path: str, limit: int) -> str | None:
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read(limit + 1)
    except OSError:
        return None
    return text if len(text) <= limit else text[:limit] + "\n[…truncated]"


def _listing(repo_path: str) -> str:
    lines: list[str] = []
    for root, dirs, files in os.walk(repo_path):
        rel = os.path.relpath(root, repo_path)
        depth = 0 if rel == "." else rel.count(os.sep) + 1
        dirs[:] = sorted(d for d in dirs if d not in _SKIP_DIRS and (not d.startswith(".") or d == ".github"))
        if depth >= 2:
            dirs[:] = []
        indent = "  " * depth
        if depth:
            lines.append(f"{indent[:-2]}{os.path.basename(root)}/")
        lines.extend(f"{indent}{name}" for name in sorted(files) if not name.startswith(".") or name.startswith(".git"))
    return "\n".join(lines)[:_TREE_CHARS]


def gather_repo_facts(repo_path: str, *, max_chars: int = _FACTS_CHARS) -> str:
    """The raw material the guide is written from. Empty when the repo has
    nothing worth describing (no files at all)."""
    sections: list[tuple[str, str]] = []

    listing = _listing(repo_path)
    if not listing.strip():
        return ""
    sections.append(("Directory listing (two levels; partial)", listing))

    # The root and each immediate subfolder — a monorepo's manifests and
    # READMEs sit a level down.
    candidates = [""] + sorted(
        d for d in os.listdir(repo_path)
        if os.path.isdir(os.path.join(repo_path, d)) and d not in _SKIP_DIRS and not d.startswith(".")
    )
    for sub in candidates:
        base = os.path.join(repo_path, sub)
        for name in _MANIFESTS:
            text = _read_head(os.path.join(base, name), _MANIFEST_CHARS)
            if text is not None:
                sections.append((os.path.join(sub, name), text))
        for name in _READMES:
            text = _read_head(os.path.join(base, name), _README_CHARS)
            if text is not None:
                sections.append((os.path.join(sub, name), text))
                break

    workflows = os.path.join(repo_path, ".github", "workflows")
    if os.path.isdir(workflows):
        for name in sorted(os.listdir(workflows))[:_MAX_WORKFLOWS]:
            if name.endswith((".yml", ".yaml")):
                text = _read_head(os.path.join(workflows, name), _WORKFLOW_CHARS)
                if text is not None:
                    sections.append((f".github/workflows/{name}", text))

    try:
        skeleton = build_codebase_skeleton(repo_path, max_chars=_SKELETON_CHARS)
    except Exception as exc:  # noqa: BLE001 — the skeleton is a nicety; the guide is still worth writing without it
        logger.warning("project guide: could not build a code skeleton for %s: %s", repo_path, exc)
        skeleton = ""
    if skeleton:
        sections.append(("Code skeleton (top-level declarations; partial)", skeleton))

    out = "\n\n".join(f"=== {title} ===\n{body}" for title, body in sections)
    return out[:max_chars]


async def generate_project_guide(repo_path: str) -> str:
    """Writes a guide for one repo. Raises GuideError rather than returning
    something half-usable — a wrong "authoritative" guide is worse than none,
    so the caller stores it only on success."""
    facts = await asyncio.to_thread(gather_repo_facts, repo_path)
    if not facts:
        raise GuideError("the repository has no files to describe")
    try:
        parsed, _usage = await chat_completion_json(
            messages=[
                {"role": "system", "content": _SYSTEM_PROMPT},
                {"role": "user", "content": f"Write AGENTS.md for this repository.\n\n{facts}"},
            ],
            response_schema=_GUIDE_SCHEMA,
            response_schema_name="project_guide",
            label="project guide",
        )
    except LlmNotConfiguredError as exc:
        raise GuideError(str(exc)) from exc
    except GenerationError as exc:
        raise GuideError(str(exc)) from exc

    body = str((parsed or {}).get("guide") or "").strip()
    if not body:
        raise GuideError("the model returned an empty guide")
    return _cap(f"{GENERATED_HEADER}\n\n{body}")


async def project_guide_for_run(sm, project_id: int, repo_roots: dict[str, str]) -> dict[str, Any]:
    """The guide to hand a story's planner, generating one first for any repo
    that lacks both its own and a stored one — when the project has
    `generate_project_guide` on. Never raises: a guide is context, and the
    run should not fail because one could not be written."""
    try:
        repos = await asyncio.to_thread(sm.list_project_repos, project_id)
        by_path = {repo["path"]: repo for repo in repos}

        if resolve_bool_config("generate_project_guide", project_id):
            for label, path in repo_roots.items():
                repo = by_path.get(path)
                if repo is None or repo.get("generated_guide") or await asyncio.to_thread(read_repo_guide, path):
                    continue
                try:
                    guide = await generate_project_guide(path)
                except GuideError as exc:
                    logger.warning("project guide: not generated for %s: %s", label, exc)
                    continue
                await asyncio.to_thread(sm.set_project_repo_guide, repo["id"], guide)
                repo["generated_guide"] = guide
                logger.info("project guide: generated for %s (%d chars)", label, len(guide))

        generated = {path: repo["generated_guide"] for path, repo in by_path.items() if repo.get("generated_guide")}
        return await asyncio.to_thread(resolve_project_guide, repo_roots, generated)
    except Exception:  # noqa: BLE001 — see the docstring
        logger.exception("project guide: could not resolve a guide for project %s", project_id)
        return {"found": False}
