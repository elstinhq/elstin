import { useState } from "react";
import { useGenerateRepoGuide, useRepoGuide, useSaveRepoGuide } from "../../hooks/useFolders";
import { useToast } from "../../lib/toast";
import type { RepoGuide } from "../../types/api";
import { Button } from "../ui/button";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "../ui/dialog";
import { Textarea } from "../ui/textarea";

// The planner and dev agents read a repo's AGENTS.md before they work. A repo
// that ships one is left alone; for one that has none, elstin can write one and
// keep it here — the repo itself is never edited. It is read as authoritative,
// so a generated guide can be read, corrected, regenerated or thrown away.

function GuideDialog({
  projectId,
  repoId,
  guide,
  onClose,
}: {
  projectId: number;
  repoId: number;
  guide: RepoGuide;
  onClose: () => void;
}) {
  const save = useSaveRepoGuide(projectId, repoId);
  const generate = useGenerateRepoGuide(projectId, repoId);
  const { showToast } = useToast();
  const [draft, setDraft] = useState(guide.content ?? "");
  const own = guide.source === "repo";
  const busy = save.isPending || generate.isPending;

  return (
    <Dialog open onOpenChange={(open) => !open && onClose()}>
      <DialogContent className="sm:max-w-2xl">
        <DialogHeader>
          <DialogTitle>Project guide</DialogTitle>
          <DialogDescription>
            {own
              ? `This repo ships its own ${guide.filename}. Planner and dev read it as is; to change it, change it in the repo.`
              : "Generated by Elstin from the repo's manifests, README and CI files. Planner and dev read it as authoritative, so fix anything wrong. The repo itself is not changed."}
          </DialogDescription>
        </DialogHeader>
        <Textarea
          value={draft}
          readOnly={own}
          onChange={(e) => setDraft(e.target.value)}
          className="max-h-[55vh] min-h-72 font-mono text-xs"
          aria-label="Project guide"
        />
        <DialogFooter>
          {own ? (
            <Button variant="outline" onClick={onClose}>
              Close
            </Button>
          ) : (
            <>
              <Button
                variant="outline"
                disabled={busy}
                loading={save.isPending && save.variables === ""}
                onClick={() =>
                  save.mutate("", {
                    onSuccess: onClose,
                    onError: (err) => showToast(err.message || "Could not discard the guide", "error"),
                  })
                }
              >
                Discard
              </Button>
              <Button
                variant="outline"
                disabled={busy}
                loading={generate.isPending}
                onClick={() =>
                  generate.mutate(undefined, {
                    onSuccess: (next) => setDraft(next.content ?? ""),
                    onError: (err) => showToast(err.message || "Could not generate a guide", "error"),
                  })
                }
              >
                Regenerate
              </Button>
              <Button
                disabled={busy || draft.trim() === (guide.content ?? "").trim()}
                loading={save.isPending && save.variables !== ""}
                onClick={() =>
                  save.mutate(draft, {
                    onSuccess: () => {
                      showToast("Guide saved", "success");
                      onClose();
                    },
                    onError: (err) => showToast(err.message || "Could not save the guide", "error"),
                  })
                }
              >
                Save
              </Button>
            </>
          )}
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

// `canGenerate` is false for a reference folder: elstin writes guides for
// repos only; a reference folder's own CLAUDE.md, if any, is read as it is.
export function RepoGuideControl({ projectId, repoId, canGenerate = true }: { projectId: number; repoId: number; canGenerate?: boolean }) {
  const guideQuery = useRepoGuide(projectId, repoId);
  const generate = useGenerateRepoGuide(projectId, repoId);
  const { showToast } = useToast();
  const [open, setOpen] = useState(false);
  const guide = guideQuery.data;
  if (!guide) return null;

  const summary =
    guide.source === "repo"
      ? `Guide: ${guide.filename}${canGenerate ? " from the repo" : ""}`
      : guide.source === "generated"
        ? "Guide: generated by Elstin"
        : canGenerate
          ? "No AGENTS.md"
          : "No CLAUDE.md or AGENTS.md";

  return (
    <div className="text-muted-foreground flex items-center gap-1 text-xs">
      <span className="whitespace-nowrap">{summary}</span>
      {guide.source === "none" && !canGenerate ? null : guide.source === "none" ? (
        <Button
          variant="link"
          size="sm"
          className="h-auto px-1 py-0 text-xs"
          loading={generate.isPending}
          title="Have Elstin write a guide for the planner and dev agents from this repo's manifests, README and CI files. Takes a minute or two. The repo is not changed."
          onClick={() =>
            generate.mutate(undefined, {
              onSuccess: () => showToast("Guide generated", "success"),
              onError: (err) => showToast(err.message || "Could not generate a guide", "error"),
            })
          }
        >
          Generate guide
        </Button>
      ) : (
        <Button variant="link" size="sm" className="h-auto px-1 py-0 text-xs" onClick={() => setOpen(true)}>
          {guide.source === "repo" ? "View" : "View / edit"}
        </Button>
      )}
      {open ? <GuideDialog projectId={projectId} repoId={repoId} guide={guide} onClose={() => setOpen(false)} /> : null}
    </div>
  );
}
