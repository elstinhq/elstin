def test_the_planner_prompt_carries_the_guide_and_flags_a_generated_one():
    from forge.agents.roles.planner_loop import _build_prompt_text

    def prompt(guide):
        return _build_prompt_text(
            user_request="do it", project_path="/p", context_bundle={"project_guide": guide},
            linked_issues_context=None, acceptance_criteria_hint=None, prior_work={}, clarification_answers=None,
        )

    generated = prompt({"found": True, "content": "USE generate:api", "generated": True})
    assert "USE generate:api" in generated and "generated by forge" in generated

    own = prompt({"found": True, "content": "USE generate:api", "generated": False})
    assert "USE generate:api" in own and "generated by forge" not in own

    assert "PROJECT ARCHITECTURE GUIDE" not in prompt({"found": False})


@pytest.mark.asyncio
@pytest.mark.usefixtures("forge_db", "fake_agents")
async def test_a_dispatched_story_hands_its_planner_the_guide(git_repo, tmp_path, project_id, monkeypatch):
    import forge.orchestration.graph as graph
    from forge.config.store import set_config
    from forge.daemon.main import poll_once

    set_config("worktrees_base_dir", str(tmp_path / "worktrees"))
    set_config("openai_api_key", "sk-test")
    Path(git_repo, "AGENTS.md").write_text("Use `npm run generate:api`; never hand-edit schema.ts.\n")

    sm = StateManager()
    sm.create_epic("ENG-1", project_id=project_id, levels=[["ENG-2"]], manual_gate=False)
    sm.set_epic_project_repo("ENG-1", sm.add_project_repo(project_id, git_repo))
    sm.create_story("ENG-2", epic_key="ENG-1", wave=0, summary="Add currency")

    seen: dict = {}
    original = graph.run_planner

    async def spy(**kwargs):
        seen.update(kwargs)
        return await original(**kwargs)

