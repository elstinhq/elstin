"""The project guide: finding a repo's own AGENTS.md, generating one for a
repo that has none, and getting it in front of the planner.

The model is faked at `chat_completion_json` throughout — what is under test
is what forge gathers, what it asks for, what it stores and when, not the
model's prose."""
